  function forYear(y) {
    const e = BG.easter(y);
    const out = FIXED.map(([m, d, title, names]) => ({ date: new Date(y, m - 1, d), title, names, movable: false }));
    MOVABLE.forEach(([off, title, names]) => out.push({ date: BG.addDays(e, off), title, names, movable: true }));
    return out.sort((a, b) => a.date - b.date);
  }

  const startOfDay = (d) => new Date(d.getFullYear(), d.getMonth(), d.getDate());

  function onDate(date) {
    const k = BG.key(date);
    return forYear(date.getFullYear()).filter((x) => BG.key(x.date) === k);
  }

  function allNames() {
    const set = new Set();
    FIXED.forEach((f) => f[3].forEach((n) => set.add(n)));
    MOVABLE.forEach((f) => f[2].forEach((n) => set.add(n)));
    return [...set].sort((a, b) => a.localeCompare(b, 'bg'));
  }

  // Търсене по име (пълно съвпадение, иначе – начало на името)
  function search(q, now) {
    q = q.trim().toLowerCase();
    if (!q) return [];
    const today = startOfDay(now);
    const hits = [];
    const seen = new Set();
    const consider = (title, names, nextFn) => {
      const exact = names.some((n) => n.toLowerCase() === q);
      const pref = names.some((n) => n.toLowerCase().startsWith(q));
      if (!(exact || (q.length >= 2 && pref))) return;
      let date = nextFn(today.getFullYear());
      if (date < today) date = nextFn(today.getFullYear() + 1);
      const id = title + '|' + names[0];
      if (seen.has(id)) return;
      seen.add(id);
      hits.push({ title, names, date, exact, days: Math.round((date - today) / 864e5) });
    };
    FIXED.forEach(([m, d, title, names]) => consider(title, names, (y) => new Date(y, m - 1, d)));
    MOVABLE.forEach(([off, title, names]) => consider(title, names, (y) => BG.addDays(BG.easter(y), off)));
    return hits.sort((a, b) => b.exact - a.exact || a.date - b.date);
  }

