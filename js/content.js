  // Събития за година (по дата)
  function events(y) {
    const map = {};
    const add = (date, title, type, extra) => {
      const k = BG.key(date) + '|' + title;
      if (!map[k]) map[k] = { date, title, types: [], ...extra };
      if (!map[k].types.includes(type)) map[k].types.push(type);
    };
    const ys = BG.year(y);
    Object.keys(ys.off).forEach((k) => { const [a, b, c] = k.split('-').map(Number); add(mk(a, b, c), ys.off[k].name, 'dayoff', { off: true }); });
    CH_FIXED.forEach(([m, d, t]) => add(mk(y, m, d), t, 'church'));
    CH_MOV.forEach(([o, t]) => add(BG.addDays(BG.easter(y), o), t, 'church'));
    NATIONAL.forEach(([m, d, t]) => add(mk(y, m, d), t, 'national'));
    const e = BG.easter(y);
    add(BG.addDays(e, -48), 'Започва Великият пост', 'fast');
    add(mk(y, 8, 1), 'Започва Успенският пост', 'fast');
    add(mk(y, 11, 15), 'Започва Коледният пост', 'fast');
    ND.forYear(y).forEach((n) => add(n.date, n.title, 'name', { names: n.names }));
    // Дублиращи се имена на празници, които вече са църковни/официални, се сливат по дата
    const byDate = {};
    Object.values(map).forEach((ev) => { (byDate[BG.key(ev.date)] = byDate[BG.key(ev.date)] || []).push(ev); });
    const out = [];
    Object.values(byDate).forEach((list) => {
      const nameEv = list.filter((x) => x.types.length === 1 && x.types[0] === 'name');
      const others = list.filter((x) => !(x.types.length === 1 && x.types[0] === 'name'));
      others.forEach((o) => out.push(o));
      nameEv.forEach((n) => out.push(n));
    });
    out.forEach((ev) => { const h = holByTitle(ev.title) || holByTitle(ev.title.replace(/ \(2-ри ден\)/, '')); if (h) ev.id = h.id; });
    return out.sort((a, b) => a.date - b.date);
  }

  function between(from, to) {
    const out = [];
    for (let y = from.getFullYear(); y <= to.getFullYear(); y++) events(y).forEach((e) => { if (e.date >= from && e.date <= to) out.push(e); });
    return out.sort((a, b) => a.date - b.date);
  }

  // Най-близкият дълъг уикенд / празнична почивка (от 3 дни, с поне един официален празник)
  function nextBreak(now) {
    const today = ND.startOfDay(now);
    let d = BG.addDays(today, 1), cur = null;
    for (let i = 0; i < 500; i++, d = BG.addDays(d, 1)) {
      if (BG.isOff(d)) {
        if (!cur) cur = { start: d, end: d, official: false };
        cur.end = d;
        if (BG.offName(d)) cur.official = true;
      } else if (cur) {
        if (cur.official && Math.round((cur.end - cur.start) / 864e5) + 1 >= 3 && !(cur.start <= today)) break;
        cur = null;
      }
    }
    if (!cur) return null;
    cur.len = Math.round((cur.end - cur.start) / 864e5) + 1;
    cur.days = Math.round((cur.start - today) / 864e5);
    return cur;
  }

