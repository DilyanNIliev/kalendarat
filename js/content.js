  function between(from, to) {
    const out = [];
    for (let y = from.getFullYear(); y <= to.getFullYear(); y++) events(y).forEach((e) => { if (e.date >= from && e.date <= to) out.push(e); });
    return out.sort((a, b) => a.date - b.date);
  }

  // Най-близкият дълъг уикенд / празнична почивка (от 3 дни, с поне един официален празник)
  function nextBreak(now) {
    const today = ND.startOfDay(now);
    let d = BG.addDays(today, 1), cur = null;
    for (let i = 0; i < 500; i++, d = BG.addDays(d, 1)) {
      if (BG.isOff(d)) {
        if (!cur) cur = { start: d, end: d, official: false };
        cur.end = d;
        if (BG.offName(d)) cur.official = true;
      } else if (cur) {
        if (cur.official && Math.round((cur.end - cur.start) / 864e5) + 1 >= 3 && !(cur.start <= today)) break;
        cur = null;
      }
    }
    if (!cur) return null;
    cur.len = Math.round((cur.end - cur.start) / 864e5) + 1;
    cur.days = Math.round((cur.start - today) / 864e5);
    return cur;
  }

